import identity from "@careeros/brand/identity.json" with { type: "json" };
import { esc } from "./html.js";
import { oneLine } from "./scrub.js";

/**
 * The "AI voice" mark on every frame of every video. The narration voice's licence (Supertonic 3, OpenRAIL-M,
 * Attachment A (e)) forbids publishing what it makes without saying plainly that it is machine generated, so the
 * mark has no off switch. The macOS `say` fallback is synthetic too, so it gets the same words.
 */
export const WATERMARK_TEXT = "AI voice";
/** Part of the expand hash (pipeline.ts stageHashes): bump when the mark changes, so earlier renders re-render. */
export const WATERMARK_VERSION = "ai-voice-v2";

/**
 * The brand mark, the same drawing as packages/brand/assets/mark.svg (generated by brand's markSvg; a test keeps the
 * two equal). Inlined because brand's markSvg pulls in React glyphs this package can't load.
 */
export const MARK_SVG = `<svg width="20" height="20" viewBox="0 0 24 24" aria-hidden="true"><defs><linearGradient id="wm-mark-g" x1="0" y1="0" x2="1" y2="1"><stop offset="0" stop-color="#f2a65a"/><stop offset="0.5" stop-color="#e8d3a8"/><stop offset="1" stop-color="#7fd1a8"/></linearGradient></defs><rect x="0" y="0" width="24" height="24" rx="7.5" fill="url(#wm-mark-g)"/><g fill="none" stroke-width="1.75" stroke-linecap="round" stroke-linejoin="round"><path d="M7 17h3v-3h3v-3h2" stroke="#0d0e11"/><circle cx="17" cy="7" r="1.25" stroke="#0d0e11" fill="#0d0e11"/></g></svg>`;

/** Top right, in the empty band above the stage's 96px safe area and far from the captions (y 896+). Last child of
 * #root with the highest z-index, so no scene, picture or the end fade ever covers it. Colours are theme.css values;
 * the backing pill is the caption pill's, so the words read on light pictures and dark scenes alike. */
export const WATERMARK_CSS = `
.ai-mark { position: absolute; top: 28px; right: 32px; z-index: 1000; display: flex; align-items: center; gap: 7px; height: 30px; padding: 0 12px 0 5px; border-radius: 999px; background: rgba(9, 12, 15, 0.6); opacity: 0.6; pointer-events: none; }
.ai-mark svg { display: block; }
.ai-mark span { font-family: "Montserrat", sans-serif; font-weight: 600; font-size: 16px; letter-spacing: 0.03em; color: #eef1f3; white-space: nowrap; }
`;

export function watermarkHtml(): string {
  return `<div id="ai-mark" class="ai-mark" aria-label="${esc(`${WATERMARK_TEXT}, ${identity.name}`)}">${MARK_SVG}<span>${esc(WATERMARK_TEXT)}</span></div>`;
}

/** The narration engine's id (narrate.py) as a person would name it. Unknown ids are shown as given, on one line. */
export function engineLabel(engine: string | undefined): string {
  if (engine === "supertonic") return "Supertonic 3";
  if (engine === "macos_say") return "macOS say";
  const raw = oneLine(String(engine ?? "")).slice(0, 60);
  return raw || "unknown engine";
}

/** ffmpeg `-metadata` pairs for the finished MP4: a title, and a comment and description that disclose the AI voice. */
export function disclosureMetadata(title: string, engine: string | undefined): string[] {
  const note = `Narration generated with an AI voice (${engineLabel(engine)}) by ${identity.name}`;
  const t = oneLine(title).slice(0, 200) || identity.name;
  return ["-metadata", `title=${t}`, "-metadata", `comment=${note}`, "-metadata", `description=${note}`];
}

/** A stream copy of `input` to `output` with the disclosure tags set (no re-encode). */
export function metadataArgs(input: string, output: string, title: string, engine: string | undefined): string[] {
  return ["-hide_banner", "-nostdin", "-v", "error", "-y", "-i", input, "-map", "0", "-c", "copy", "-map_metadata", "0",
    ...disclosureMetadata(title, engine), "-movflags", "+faststart", output];
}
