#!/usr/bin/env node
// Builds dist/tokens.css and dist/tokens.ts from the DTCG sources in tokens/.
// Style Dictionary parses DTCG, resolves references and names tokens (kebab case);
// this script writes the two files deterministically (sorted, no timestamps).
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import StyleDictionary from "style-dictionary";

const pkg = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const src = (f) => path.join(pkg, "tokens", f);
const THEMES = [
  { name: "graphite", file: "semantic.graphite.json", selector: ':root, [data-theme="graphite"]' },
  { name: "paper", file: "semantic.paper.json", selector: '[data-theme="paper"]' },
];
const HEADER = "Generated by packages/brand/scripts/build-tokens.mjs from packages/brand/tokens/*.json. Do not edit.";

async function tokensFor(files) {
  const sd = new StyleDictionary({
    source: files.map(src),
    log: { verbosity: "silent", warnings: "disabled" },
    platforms: { css: { transforms: ["name/kebab"] } },
  });
  const { allTokens } = await sd.getPlatformTokens("css");
  return allTokens
    .map((t) => ({ name: t.name, value: String(t.$value ?? t.value), core: t.filePath.endsWith("core.json") }))
    .sort((a, b) => a.name.localeCompare(b.name));
}

const block = (selector, list) => `${selector} {\n${list.map((t) => `  --${t.name}: ${t.value};`).join("\n")}\n}\n`;
const record = (list) => JSON.stringify(Object.fromEntries(list.map((t) => [t.name, t.value])), null, 2);

export async function buildTokens() {
  const core = await tokensFor(["core.json"]);
  const themed = {};
  for (const th of THEMES) themed[th.name] = (await tokensFor(["core.json", th.file, "component.json"])).filter((t) => !t.core);
  const css = [`/* ${HEADER} */\n`, block(":root", core), ...THEMES.map((th) => block(th.selector, themed[th.name]))].join("\n");
  const ts = [
    `// ${HEADER}`,
    `export const core = ${record(core)} as const;`,
    ...THEMES.map((th) => `export const ${th.name} = ${record(themed[th.name])} as const;`),
    "export const themes = { graphite, paper } as const;",
    "export type ThemeName = keyof typeof themes;",
    "export type ThemeTokenName = keyof typeof graphite;",
    "export type CoreTokenName = keyof typeof core;",
  ].join("\n\n") + "\n";
  return { css, ts };
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const { css, ts } = await buildTokens();
  fs.mkdirSync(path.join(pkg, "dist"), { recursive: true });
  fs.writeFileSync(path.join(pkg, "dist", "tokens.css"), css);
  fs.writeFileSync(path.join(pkg, "dist", "tokens.ts"), ts);
  console.log("wrote packages/brand/dist/tokens.css and tokens.ts");
}
